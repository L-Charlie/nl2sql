"""
agent_team 包 —— 多智能体 NL2SQL 系统的智能体团队包。

本包包含以下核心组件，它们协作将自然语言问题转换为 SQL 查询：

┌──────────────────────────────────────────────────────────────┐
│  Planner（规划器）                                           │
│   - 将用户的自然语言问题拆解为可执行的子步骤                  │
│   - 生成查询计划（query plan）                                │
├──────────────────────────────────────────────────────────────┤
│  Builder（构建器）                                           │
│   - 根据 Planner 的查询计划，实际构建 SQL 语句               │
│   - 负责表选择、列映射、JOIN 等 SQL 细节                     │
├──────────────────────────────────────────────────────────────┤
│  Refiner（精炼器）                                           │
│   - 验证 SQL 的正确性（语法、语义、业务逻辑）                │
│   - 使用 refiner_decision_engine 进行零 LLM 的修复决策       │
│   - 如果 SQL 有问题，决定是否需要重新规划或重新构建          │
├──────────────────────────────────────────────────────────────┤
│  KnowledgeKeeper（知识守护者）                               │
│   - 维护知识图谱（knowledge graph）                          │
│   - 提供 Schema 信息、业务规则等上下文                       │
├──────────────────────────────────────────────────────────────┤
│  SchemaLinker（Schema 链接器）                               │
│   - 将自然语言中的字段/表名与数据库 Schema 关联起来          │
│   - 处理同义词、别名、中文→英文的映射                       │
├──────────────────────────────────────────────────────────────┤
│  build_indices（索引构建脚本）                               │
│   - 从源文件构建知识图谱 JSON、嵌入索引和案例库              │
└──────────────────────────────────────────────────────────────┘

典型工作流程：
  用户提问 → Planner 分析 → Builder 构建 SQL → Refiner 验证
  → 如有问题 → Refiner 决策引擎判断修复层级 → Planner/Builder 修复
  → 最终输出正确 SQL

所有组件共享 KnowledgeKeeper 中的知识图谱和嵌入索引，
以确保对整个数据库 Schema 的一致性理解。
"""
